"""Syncall feature-flag setup helpers.

Mirrors ``taskwarrior_setup.py`` / ``gcal_setup.py``: env-var flag check,
path resolution, and a ``build_syncall()`` step invoked
from ``setup_workspace.setup_workspace()``. Nothing here launches the
daemon — that is ``syncall_daemon.main()`` and is wired by ``start.py``.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass
from pathlib import Path
from typing import Mapping

log = logging.getLogger(__name__)

__all__ = [
    "SYNCALL_ENV_VARS",
    "SyncallPaths",
    "build_syncall",
    "is_syncall_enabled",
    "resolve_syncall_paths",
    "write_repo_scoped_taskrc",
]

SYNCALL_ENV_VARS: tuple[str, ...] = (
    "SYNCALL_ENABLED",
    "SYNCALL_GCAL_CALENDAR",
    "SYNCALL_COMBINATION_NAME",
    "SYNCALL_RESOLUTION_STRATEGY",
    "SYNCALL_POLL_SECONDS",
    "SYNCALL_OAUTH_PORT",
    "SYNCALL_VERBOSE",
)


@dataclass(frozen=True)
class SyncallPaths:
    """Resolved filesystem locations syncall touches inside the repo."""

    oauth_credentials: Path
    cache_dir: Path
    xdg_config_home: Path
    taskrc_path: Path
    tw_data_dir: Path
    log_path: Path
    vendor_dir: Path


def is_syncall_enabled(env: Mapping[str, str]) -> bool:
    """True when ``SYNCALL_ENABLED=true`` (case-insensitive)."""
    return env.get("SYNCALL_ENABLED", "").strip().lower() == "true"


def resolve_syncall_paths(
    env: Mapping[str, str], repo_root: Path, tw_data_dir: Path,
) -> SyncallPaths:
    """Resolve all paths syncall reads or writes, all repo-scoped.

    OAuth credentials default to empty Path — callers that need the value
    must check ``path.as_posix()`` against the empty string. We use the
    same ``GOOGLE_OAUTH_CREDENTIALS`` var Task 14 established, reusing the
    desktop-client JSON for both read-side MCP and write-side syncall.

    The cache dir (``workspace/data/syncall_cache/``) holds syncall's
    combinations YAML + per-side serdes pickles. It doubles as the
    ``XDG_CONFIG_HOME`` we pass into the daemon subprocess so syncall
    writes ``syncall/`` under it rather than under ``~/.config/``.

    The taskrc path is a tiny generated file that tells ``taskw_ng`` (the
    library syncall's TW side uses) where the Taskwarrior data dir is.
    Pointed at via ``TASKRC`` env var in the subprocess; never touches
    ``~/.taskrc``.
    """
    data_dir = repo_root / "workspace" / "data"
    cache_dir = data_dir / "syncall_cache"
    creds_raw = env.get("GOOGLE_OAUTH_CREDENTIALS", "").strip()
    oauth_credentials = Path(creds_raw).expanduser() if creds_raw else Path("")
    return SyncallPaths(
        oauth_credentials=oauth_credentials,
        cache_dir=cache_dir,
        xdg_config_home=cache_dir,
        taskrc_path=cache_dir / "taskrc",
        tw_data_dir=tw_data_dir,
        log_path=data_dir / "syncall_daemon.log",
        vendor_dir=repo_root / "vendor" / "syncall",
    )


def _ensure_private_dir(path: Path) -> None:
    """Create ``path`` and best-effort chmod 0700. Windows no-ops."""
    path.mkdir(parents=True, exist_ok=True)
    try:
        path.chmod(0o700)
    except (NotImplementedError, OSError):
        log.info("Could not chmod %s to 0o700 on this platform", path)


def write_repo_scoped_taskrc(taskrc_path: Path, tw_data_dir: Path) -> None:
    """Write a minimal taskrc pointing Taskwarrior at the repo data dir.

    syncall's ``taskw_ng`` requires *some* taskrc to exist; we do not want
    it reading ``~/.taskrc`` and picking up user-specific context filters
    or UDAs that would confuse the sync. The file is regenerated on every
    ``setup_workspace`` run so the resolved path always matches the
    current ``TASKWARRIOR_DATA_DIR``.
    """
    taskrc_path.parent.mkdir(parents=True, exist_ok=True)
    body = (
        "# Auto-generated by syncall_setup.py. Do not edit by hand.\n"
        "# Regenerated on every setup_workspace run.\n"
        f"data.location={tw_data_dir.as_posix()}\n"
        "confirmation=off\n"
        "recurrence=off\n"
        "verbose=nothing\n"
    )
    taskrc_path.write_text(body, encoding="utf-8")


def _warn_if_oauth_missing(oauth_credentials: Path) -> None:
    if oauth_credentials == Path("") or not oauth_credentials.exists():
        log.warning(
            "SYNCALL_ENABLED=true but GOOGLE_OAUTH_CREDENTIALS points at a "
            "missing file (%s). The daemon will keep retrying but every "
            "sync will fail until you complete the Google OAuth consent "
            "flow. See workspace/SYNCALL.md for the first-run ritual.",
            oauth_credentials or "<unset>",
        )


def build_syncall(
    env: Mapping[str, str], repo_root: Path, tw_data_dir: Path,
) -> SyncallPaths | None:
    """Create repo-scoped syncall dirs + taskrc when the flag is on.

    Short-circuits to ``None`` when ``SYNCALL_ENABLED`` is absent or
    false; returns the resolved ``SyncallPaths`` otherwise so callers can
    log the locations. Never raises on a missing OAuth creds file — logs
    a warning and continues, because the file is only needed at the
    moment the user runs the first interactive sync, not at setup time.
    """
    if not is_syncall_enabled(env):
        log.info("SYNCALL_ENABLED=false — skipping syncall setup")
        return None
    paths = resolve_syncall_paths(env, repo_root, tw_data_dir)
    _ensure_private_dir(paths.cache_dir)
    write_repo_scoped_taskrc(paths.taskrc_path, paths.tw_data_dir)
    _warn_if_oauth_missing(paths.oauth_credentials)
    log.info("Syncall cache dir ready at %s", paths.cache_dir)
    log.info("Syncall repo-scoped taskrc written at %s", paths.taskrc_path)
    return paths
